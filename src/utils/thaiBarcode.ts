// แปลงอักขระแป้นพิมพ์ไทย (Kedmanee) → ASCII สำหรับการสแกนบาร์โค้ด
// แก้ปัญหา: เมื่อ OS ตั้ง input เป็นไทย เครื่องสแกนจะส่งอักขระไทยแทนตัวเลข/สัญลักษณ์
const thaiToQwertyMap: Record<string, string> = {
  'ๅ': '1', '/': '2', '-': '3', 'ภ': '4', 'ถ': '5', 'ุ': '6', 'ึ': '7', 'ค': '8', 'ต': '9', 'จ': '0',
  'ข': '-', 'ช': '_',
  '+': '+', '๑': '!', '๒': '@', '๓': '#', '๔': '$', 'ู': '%', '฿': '^', '๕': '&', '๖': '*', '๗': '(', '"': ')',
};

/** แปลงสตริงบาร์โค้ดที่อาจถูกพิมพ์ด้วยแป้นไทยให้กลับเป็น ASCII (อักขระที่ไม่อยู่ในตารางคงเดิม) */
export const translateThaiBarcode = (raw: string): string =>
  raw.split('').map((c) => thaiToQwertyMap[c] ?? c).join('');
